/**
 * AETERNA - emergency runtime artefact freshness (R9-A65).
 *
 * The standalone Emergency Runtime must always be generated from its current
 * source by `npm run build:emergency`. A committed copy under `public/scripts/`
 * used to shadow the build and could be shipped stale, so it must not exist.
 *
 * `npm test` runs `pretest` (build:emergency) before this suite, so `dist/` is
 * always at least as new as the source in the supported flow.
 */

import { describe, expect, it } from "vitest";
import { existsSync, readFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, "../../..");

const PUBLIC_BUNDLE = resolve(REPO_ROOT, "public/scripts/emergency-runtime.js");
const DIST_BUNDLE = resolve(REPO_ROOT, "dist/scripts/emergency-runtime.js");
const ENTRY_SOURCE = resolve(REPO_ROOT, "src/emergency/emergencyRuntime.ts");

describe("R9-A65 emergency runtime artefact", () => {
  it("does not ship a stale committed copy under public/scripts", () => {
    expect(existsSync(PUBLIC_BUNDLE)).toBe(false);
  });

  it("is generated by the standalone emergency build", () => {
    expect(existsSync(DIST_BUNDLE)).toBe(true);
  });

  it("is never older than its source", () => {
    const built = statSync(DIST_BUNDLE).mtimeMs;
    const source = statSync(ENTRY_SOURCE).mtimeMs;

    expect(built).toBeGreaterThanOrEqual(source);
  });

  it("stays a single self-contained bundle (no dynamic chunk imports)", () => {
    const bundle = readFileSync(DIST_BUNDLE, "utf8");

    expect(bundle).not.toMatch(/import\("/);
    expect(bundle.length).toBeGreaterThan(10_000);
  });
});